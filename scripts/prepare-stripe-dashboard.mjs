import { readFile, mkdir, writeFile } from "node:fs/promises";

// Dashboard deployments can paste one file per function; the source keeps shared
// validation in one place. No credentials are bundled into these files.
const root = new URL("../", import.meta.url);
const target = new URL("../supabase/dashboard-deploy/", import.meta.url);
await mkdir(target, { recursive: true });
const read = (path) => readFile(new URL(path, root), "utf8");
const validation = await read("supabase/functions/_shared/payment-validation.ts");
const shared = (await read("supabase/functions/_shared/checkout.ts")).replace(/^import .*from "\.\/payment-validation\.ts";\n/m, "");
for (const name of ["create-checkout-session", "cancel-checkout-session", "verify-checkout-session", "stripe-webhook"]) {
  const handler = (await read(`supabase/functions/${name}/index.ts`)).replace(/^import .*from "\.\.\/_shared\/[^\"]+";\n/gm, "");
  const source = name === "stripe-webhook" ? validation + "\n" + handler : validation + "\n" + shared + "\n" + handler;
  await writeFile(new URL(`${name}.ts`, target), "// Generated by scripts/prepare-stripe-dashboard.mjs. Do not edit this copy.\n" + source);
}
console.log("Prepared four single-file Stripe sandbox functions for the Supabase dashboard.");
